"""Ошибки категорий. Роутеры переводят их в HTTP-коды, текст показывается админу."""


class InvalidCategoryError(ValueError):
    """Категорию нельзя сохранить: адрес занят, родитель не подходит и т.п."""


class CategoryInUseError(ValueError):
    """Категорию нельзя удалить: в ней есть подкатегории или объявления."""
